#!/usr/bin/env python3
"""F5.12: writes docs/rensga-engine/api-availability.md from tools/cooker/data/profile_defaults.json.

Usage: gen_api_availability.py [--check]   (--check exits 1 when the committed file differs from the data)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DATA = ROOT / "tools/cooker/data/profile_defaults.json"
OUT = ROOT / "docs/rensga-engine/api-availability.md"
PROFILES = [("psx", "PSX"), ("psp", "PSP"), ("ps2", "PS2")]
LIMITS = [("maxLightsPerObject", "Lights per object"), ("maxBonesPerDraw", "Bones per draw (0 = not batched)"),
          ("maxSkinnedJoints", "Skinned joints per skeleton (0 = none)"), ("maxTextureSize", "Largest texture edge (px)"),
          ("ramLimitBytes", "Device RAM limit (bytes, 0 = not checked)")]


def render():
    d = json.loads(DATA.read_text())
    prof = d["profiles"]
    info = d["featureInfo"]
    o = []
    o.append("<!-- GENERATED by tools/docs/gen_api_availability.py from tools/cooker/data/profile_defaults.json. Do not edit by hand. -->\n")
    o.append("# API availability by profile\n")
    o.append("A feature the profile lacks fails to compile in a script, with a hint that names the fix (`RENSGA_REQUIRES_FEATURE`, "
             "api-rules.md section 6), and the cooker refuses a scene whose components need it. Windows, Linux and Android builds of a "
             "project keep the features of the project's profile, so a script behaves the same on the console and on the PC.\n")
    o.append("A project can override both tables in `ProjectSettings/ConsoleTarget.json` with `\"features\"` and `\"limits\"`.\n")
    o.append("## Features\n")
    o.append("| Feature | API | " + " | ".join(n for _, n in PROFILES) + " | If missing |")
    o.append("| --- | --- | " + " | ".join("---" for _ in PROFILES) + " | --- |")
    for name, i in info.items():
        cells = ["yes" if name in prof[p]["features"] else "no" for p, _ in PROFILES]
        o.append(f"| `{name}` | {i['api']} | " + " | ".join(cells) + f" | {i['fix']} |")
    o.append("\n## Limits\n")
    o.append("| Limit | " + " | ".join(n for _, n in PROFILES) + " |")
    o.append("| --- | " + " | ".join("---" for _ in PROFILES) + " |")
    for key, label in LIMITS:
        o.append(f"| {label} | " + " | ".join(str(prof[p]["limits"].get(key, 0)) for p, _ in PROFILES) + " |")
    o.append("\n## What each feature covers\n")
    for name, i in info.items():
        o.append(f"- `{name}`: {i['what']}.")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
