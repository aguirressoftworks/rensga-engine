// MVP-16: ConsoleTarget.json loader and console_target.gen.h generator.
#include <ctype.h>

#include <fstream>
#include <sstream>
#include <stdexcept>

#include <nlohmann/json.hpp>

#include "rensga/cooker/cooker.h"

namespace rensga {

ConsoleTargetData loadConsoleTarget(const std::filesystem::path& file) {
  using nlohmann::json;
  std::ifstream in(file);
  if (!in) throw std::runtime_error(file.string() + ": cannot open");
  ConsoleTargetData t;
  try {
    json j = json::parse(in);
    if (j.at("format").get<int>() != 1) throw std::runtime_error("unsupported format version");
    t.profile = j.at("profile").get<std::string>();
    t.scalar = j.at("scalar").get<std::string>();
    if (t.scalar != "float" && t.scalar != "fixed") throw std::runtime_error("scalar must be 'float' or 'fixed'");
    t.width = j.at("resolution").at(0).get<uint32_t>();
    t.height = j.at("resolution").at(1).get<uint32_t>();
    const json& b = j.at("budgets");
    t.ramBytes = b.at("ramBytes").get<uint64_t>();
    t.vramBytes = b.at("vramBytes").get<uint64_t>();
    t.trianglesPerFrame = b.at("trianglesPerFrame").get<uint64_t>();
    t.maxObjects = b.at("maxObjects").get<uint64_t>();
    t.maxComponentsPerType = b.at("maxComponentsPerType").get<uint64_t>();
    t.depth = j.value("depth", "zbuffer");
    t.media = j.value("media", "");
    for (const json& c : j.at("allowedComponents")) t.allowedComponents.push_back(c.get<std::string>());
    if (j.contains("tessellation")) {
      t.sphereSegments = j["tessellation"].value("sphereSegments", 12);
      t.capsuleSegments = j["tessellation"].value("capsuleSegments", 12);
    }
  } catch (const std::exception& e) {
    throw std::runtime_error(file.string() + ": " + e.what());
  }
  return t;
}

std::string generateConsoleTargetHeader(const ConsoleTargetData& t) {
  std::string up;
  for (char c : t.profile) up += static_cast<char>(toupper(static_cast<unsigned char>(c)));
  std::ostringstream o;
  o << "// Generated by rensga-cooker from ProjectSettings/ConsoleTarget.json. Do not edit.\n"
       "#pragma once\n"
       "#define ENGINE_PROFILE_" << up << " 1\n"
       "#define ENGINE_SCALAR_" << (t.scalar == "float" ? "FLOAT" : "FIXED") << " 1\n"
       "namespace rensga { namespace console_target {\n"
       "constexpr const char* kProfile = \"" << t.profile << "\";\n"
       "constexpr unsigned kScreenWidth = " << t.width << ";\n"
       "constexpr unsigned kScreenHeight = " << t.height << ";\n"
       "constexpr unsigned kRamBytes = " << t.ramBytes << "u;\n"
       "constexpr unsigned kVramBytes = " << t.vramBytes << "u;\n"
       "constexpr unsigned kTrianglesPerFrame = " << t.trianglesPerFrame << "u;\n"
       "constexpr unsigned kMaxObjects = " << t.maxObjects << "u;\n"
       "constexpr unsigned kMaxComponentsPerType = " << t.maxComponentsPerType << "u;\n"
       "constexpr int kSphereSegments = " << t.sphereSegments << ";\n"
       "constexpr int kCapsuleSegments = " << t.capsuleSegments << ";\n"
       "} }\n";
  return o.str();
}

}  // namespace rensga
