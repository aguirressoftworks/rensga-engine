def main(out):
    results, errors = validate()
    if errors:
        for msg in errors:
            print("brand check failed:", msg, file=sys.stderr)
        sys.exit(1)
    brand = os.path.join(out, "brand")
    os.makedirs(brand, exist_ok=True)
    files = {
        "visual-identity.html": render_html(results),
        "visual-identity.md": render_md(results),
        "palette.json": json.dumps(to_json(results), ensure_ascii=False, indent=2) + "\n",
        "rensga-tokens.css": tokens_css(),
    }
    for _, path, _, mono, _ in B.LOGO["variants"]:
        if mono:
            files[os.path.basename(path)] = MONO.format(c=color(mono))
    for name, text in files.items():
        with open(os.path.join(brand, name), "w", encoding="utf-8") as f:
            f.write(text)
    print(f"wrote {len(files)} files into {brand} ({len(results)} contrast checks passed)")


