def color(ref, theme="dark"):
    """Resolve a hex value, a palette ref ("pequi.500") or a token name to hex."""
    if ref.startswith("#"):
        return ref.lower()
    if ref in PALETTE:
        return PALETTE[ref]
    if ref in TOKEN:
        return color(TOKEN[ref][theme], theme)
    raise KeyError(f"unknown color reference: {ref}")


def luminance(hx):
    r, g, b = (int(hx[i:i + 2], 16) / 255 for i in (1, 3, 5))
    lin = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def contrast(a, b):
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def ink(bg):
    """Label color that reads best on bg."""
    dark, light = PALETTE["soil.900"], "#ffffff"
    return dark if contrast(dark, bg) >= contrast(light, bg) else light


def target_hex(t):
    return color(t[3])


def validate():
    results, errors = [], []

    def check(theme, fg_name, bg_name, fg, bg, minimum):
        r = contrast(fg, bg)
        results.append({"theme": theme, "fg": fg_name, "bg": bg_name, "min": minimum, "ratio": round(r, 2), "pass": r >= minimum})
        if r < minimum:
            errors.append(f"{theme}: {fg_name} on {bg_name} is {r:.2f}:1, needs {minimum}:1")

    for hx in list(PALETTE.values()) + [t["light"] for t in TOKEN.values()] + [t["dark"] for t in TOKEN.values()]:
        if hx.startswith("#") and (len(hx) != 7 or any(ch not in "0123456789abcdefABCDEF" for ch in hx[1:])):
            errors.append(f"bad hex value: {hx}")
    if errors:
        return results, errors
    for theme in THEMES:
        for fg, bg, minimum in B.CHECKS:
            check(theme, fg, bg, color(fg, theme), color(bg, theme), minimum)
    for t in B.TARGETS:
        check("both", "white", f"target {t[1]}", "#ffffff", target_hex(t), 4.5)
    for col, ref, carries_text in B.EDITOR:
        if carries_text:
            check("editor", "text", col, color("text", "dark"), color(ref, "dark"), 4.5)
    icon = build.ICON.lower()
    for part, ref in B.LOGO_PARTS:
        if color(ref) not in icon:
            errors.append(f"icon part {part}: {ref} ({color(ref)}) does not appear in build.ICON")
    return results, errors


# ---------- palette.json and CSS ----------

def to_json(results):
    return {
        "ramps": [{"key": r["key"], "name": r["name"], "source": r["source"], "use": r["use"],
                   "steps": [{"step": s, "hex": hx.lower(), "icon": ICON_PARTS.get(f'{r["key"]}.{s}', [])} for s, hx in r["steps"]]}
                  for r in B.RAMPS],
        "targets": [{"key": k, "target": lbl, "name": n, "hex": color(ref), "source": src} for k, lbl, n, ref, src in B.TARGETS],
        "tokens": [{"name": n, "light": color(t["light"], "light"), "dark": color(t["dark"], "dark"),
                    "light_ref": t["light"], "dark_ref": t["dark"], "use": t["use"]} for n, t in TOKEN.items()],
        "editor": [{"imgui": col, "ref": ref, "hex": color(ref, "dark")} for col, ref, _ in B.EDITOR],
        "icon": [{"part": p, "ref": ref, "hex": color(ref)} for p, ref in B.LOGO_PARTS],
        "contrast": results,
    }


def css_value(ref):
    return f"var(--rg-{ref.replace('.', '-')})" if ref in PALETTE else ref.lower()


def tokens_css():
    out = ["/* Rensga Engine design tokens. Generated by roadmaps/src/build_brand.py from data_brand.py; do not edit. */",
           ":root{"]
    for r in B.RAMPS:
        out += [f'  --rg-{r["key"]}-{s}:{hx.lower()};' for s, hx in r["steps"]]
    out += [f"  --rg-target-{t[0]}:{target_hex(t)};" for t in B.TARGETS]
    out += [f'  --rg-{n}:{css_value(t["light"])};' for n, t in TOKEN.items()]
    out.append("}")
    dark = "\n".join(f'  --rg-{n}:{css_value(t["dark"])};' for n, t in TOKEN.items())
    out.append(f'@media (prefers-color-scheme:dark){{:root:not([data-theme="light"]){{\n{dark}\n}}}}')
    out.append(f':root[data-theme="dark"]{{\n{dark}\n}}')
    return "\n".join(out) + "\n"


